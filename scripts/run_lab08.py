#!/usr/bin/env python3
"""Reproducible local checks for Lab 8. No live LLM API call is made."""
from pathlib import Path
import argparse, json, re, time, sys
from rdflib import Graph, Namespace, RDF, RDFS, OWL
BASE=Path(__file__).resolve().parents[1]
EX=Namespace('http://example.org/ecommerce-recommendations#')
PFX='PREFIX : <http://example.org/ecommerce-recommendations#>\n'

def load_graph(path):
    g=Graph(); g.parse(path,format='turtle'); return g

def check_data():
    g=load_graph(BASE/'data/kb.ttl')
    jsonld=json.loads((BASE/'data/kb.jsonld').read_text(encoding='utf-8'))
    # Count JSON-LD nodes recursively enough for this serializer's top-level @graph
    nodes=jsonld.get('@graph',[]) if isinstance(jsonld,dict) else jsonld
    report=f"""# Dataset check\n\n- Turtle parse: PASS\n- Triple count: **{len(g)}**\n- Unique subjects: {len(set(g.subjects()))}\n- Declared OWL classes: {len(set(g.subjects(RDF.type, OWL.Class)))}\n- JSON-LD top-level entities: {len(nodes) if isinstance(nodes,list) else 1}\n- Dataset version: 1.0-lab08\n- Generated: 2026-10-28\n\nThe dataset derives from the Lab 7 ontology and adds synthetic demonstration individuals.\n"""
    (BASE/'reports/data_check.md').write_text(report,encoding='utf-8')
    print(report)

def run_queries():
    g=load_graph(BASE/'data/kb.ttl')
    files=sorted((BASE/'queries').glob('*.rq'))
    out=['# SPARQL results (local run)','',f'- Dataset triples: {len(g)}','- Generated by rdflib; execution times are environment-specific.','']
    for path in files:
        q=path.read_text(encoding='utf-8')
        if 'SERVICE <https://query.wikidata.org/sparql>' in q:
            out += [f'## {path.name}','- Status: NOT EXECUTED by local harness (requires a federated endpoint and network access).','- Expected interpretation: only return rows when the dataset includes Schema.org category links and Wikidata endpoint is reachable.','']
            continue
        try:
            start=time.perf_counter(); res=g.query(q); elapsed=(time.perf_counter()-start)*1000
            if res.type=='CONSTRUCT': rows=list(res.graph); preview='\n'.join(str(x) for x in rows[:5]); n=len(rows)
            elif res.type=='ASK': n=int(bool(res)); preview=str(bool(res))
            else:
                rows=list(res); n=len(rows); preview='\n'.join(' | '.join(str(v) if v is not None else 'UNBOUND' for v in row) for row in rows[:5])
            out += [f'## {path.name}',f'- Status: PASS',f'- Result count: {n}',f'- Execution time: {elapsed:.3f} ms','- Sample:', '```text',preview or '(no rows)','```','']
        except Exception as e: out += [f'## {path.name}',f'- Status: ERROR — {e}','']
    # optimize comparison: full scan query vs bounded projection
    q1=PFX+'SELECT ?p ?name WHERE { ?p a :Product ; :productName ?name }'
    q2=PFX+'SELECT ?p ?name WHERE { ?p a :Product ; :productName ?name } LIMIT 10'
    times=[]
    for label,q in [('baseline no limit',q1),('optimized bounded output',q2)]:
        start=time.perf_counter(); rr=list(g.query(q)); ms=(time.perf_counter()-start)*1000; times.append((label,ms,len(rr)))
    out += ['## Query optimization timing comparison','', '| Variant | Time (ms) | Rows |','|---|---:|---:|']
    out += [f'| {lab} | {ms:.3f} | {n} |' for lab,ms,n in times]
    out += ['', 'Interpretation: LIMIT reduces returned rows and output work; it does not guarantee lower execution time for every store or query plan. Compare repeated runs in the same environment before making a performance claim.','']
    (BASE/'reports/sparql_results.md').write_text('\n'.join(out),encoding='utf-8')
    print('\n'.join(out))

def run_shacl():
    try: from pyshacl import validate
    except ImportError:
        print('pyshacl is not installed. Run: python -m pip install pyshacl'); return 2
    shapes=load_graph(BASE/'shapes/shapes.ttl')
    summaries=[]
    for name in ['valid_data.ttl','invalid_data.ttl']:
        data=load_graph(BASE/'tests'/name)
        conforms, report_graph, report_text=validate(data_graph=data,shacl_graph=shapes, inference='rdfs')
        target=BASE/'reports'/('shacl_'+name.replace('.ttl','.ttl'))
        target.write_text(report_graph if isinstance(report_graph,str) else report_graph.serialize(format='turtle'),encoding='utf-8')
        results=list(report_graph.subjects(RDF.type, Namespace('http://www.w3.org/ns/shacl#').ValidationResult))
        summaries.append((name,conforms,len(results),str(target.relative_to(BASE))))
    out=['# SHACL validation results','']
    for name,conforms,count,path in summaries: out += [f'## {name}',f'- Conforms: **{conforms}**',f'- Validation results: {count}',f'- Report: `{path}`','']
    out += ['Expected check: valid_data.ttl should conform; invalid_data.ttl should fail and report multiple defects. If not, inspect `shapes/shapes.ttl` and the generated reports.','']
    (BASE/'reports/shacl_run.md').write_text('\n'.join(out),encoding='utf-8'); print('\n'.join(out))
    return 0 if summaries[0][1] and not summaries[1][1] and summaries[1][2]>=3 else 1

def evaluate_t2s():
    g=load_graph(BASE/'data/kb.ttl')
    rows=[json.loads(x) for x in (BASE/'tests/t2s.jsonl').read_text(encoding='utf-8').splitlines() if x.strip()]
    # Improved deterministic intent-to-query map; baseline covers only easy questions.
    intents={
      'count_products':PFX+'SELECT (COUNT(?p) AS ?count) WHERE { ?p a :Product }',
      'list_products':PFX+'SELECT ?p ?name WHERE { ?p a :Product ; :productName ?name } LIMIT 100',
      'list_customer_ids':PFX+'SELECT ?c ?id WHERE { ?c a :Customer ; :customerId ?id } LIMIT 100',
      'high_stock':PFX+'SELECT ?p ?name ?stock WHERE { ?p a :Product ; :productName ?name ; :hasInventory ?i . ?i :stockQuantity ?stock . FILTER(?stock > 10) } LIMIT 100',
      'recommendations':PFX+'SELECT ?r ?c ?p ?score WHERE { ?r a :Recommendation ; :generatedFor ?c ; :recommendsProduct ?p ; :recommendationScore ?score } LIMIT 100',
      'average_price':PFX+'SELECT (AVG(?amount) AS ?avg) WHERE { ?o a :Offer ; :hasPrice ?price . ?price :priceAmount ?amount }',
      'high_score_exists':PFX+'ASK { ?r a :Recommendation ; :recommendationScore ?score . FILTER(?score > 0.7) }',
      'customer_emails_optional':PFX+'SELECT ?c ?id ?email WHERE { ?c a :Customer ; :customerId ?id . OPTIONAL { ?c :email ?email } } LIMIT 100',
      'product_prices':PFX+'SELECT ?p ?name ?amount ?currency WHERE { ?p a :Product ; :productName ?name ; :hasOffer ?o . ?o :hasPrice ?price . ?price :priceAmount ?amount ; :currency ?currency } LIMIT 100',
      'count_customers':PFX+'SELECT (COUNT(?c) AS ?count) WHERE { ?c a :Customer }',
      'recommendations_sorted':PFX+'SELECT ?r ?score WHERE { ?r a :Recommendation ; :recommendationScore ?score } ORDER BY DESC(?score) LIMIT 100',
      'product_categories':PFX+'SELECT ?p ?cat WHERE { ?p a :Product ; :belongsToCategory ?cat } LIMIT 100',
      'minimum_price':PFX+'SELECT (MIN(?amount) AS ?min) WHERE { ?p a :Price ; :priceAmount ?amount }',
      'maximum_price':PFX+'SELECT (MAX(?amount) AS ?max) WHERE { ?p a :Price ; :priceAmount ?amount }',
      'zero_stock':PFX+'SELECT ?p ?id ?name WHERE { ?p a :Product ; :productId ?id ; :productName ?name ; :hasInventory ?i . ?i :stockQuantity 0 } LIMIT 100'}
    easy={'count_products','list_products','list_customer_ids','count_customers'}
    results={}
    for phase in ['baseline','improved']:
      vals=[]
      for item in rows:
        candidate=intents.get(item['intent']) if phase=='improved' or item['intent'] in easy else None
        syntax=False; schema=False; correct=False; err=''
        if candidate:
          try:
            parsed=g.query(candidate); syntax=True
            pred_names=set(re.findall(r':([A-Za-z][A-Za-z0-9_]*)',candidate))
            schema_names={str(s).split('#')[-1] for s in g.subjects() if str(s).startswith(str(EX))}
            schema=all(p in schema_names or p in {'Product','Customer','Recommendation','Price','Offer','Inventory','CustomerProfile','ProductCategory','hasInventory','hasOffer','hasPrice','priceAmount','stockQuantity','productName','productId','customerId','hasProfile','generatedFor','recommendsProduct','recommendationScore','belongsToCategory','currency'} for p in pred_names)
            list(parsed) if getattr(parsed,'type',None)!='ASK' else bool(parsed)
            correct=syntax and schema
          except Exception as e: err=str(e)
        vals.append({'id':item['id'],'intent':item['intent'],'syntax':syntax,'schema':schema,'correct':correct,'error':err or ('intent not mapped by baseline' if not candidate else '')})
      results[phase]=vals
    def rate(k): return sum(v[k] for v in results[phase])/len(rows)
    out=['# Text-to-SPARQL evaluation','',f'- Test questions: {len(rows)}','', '| Metric | Baseline | Improved |','|---|---:|---:|']
    for k,label in [('syntax','Syntax-valid fraction'),('schema','Schema-valid fraction'),('correct','Correct supported intent/result fraction')]:
      out.append(f'| {label} | {sum(v[k] for v in results["baseline"])/len(rows):.1%} | {sum(v[k] for v in results["improved"])/len(rows):.1%} |')
    out += ['', '## Failure review (based on actual harness output)','']
    fails=[v for v in results['baseline'] if not v['correct']]
    if fails:
      for v in fails[:5]: out.append(f"- **{v['id']} / {v['intent']}**: {v['error'] or 'baseline did not produce a valid candidate'}. Category: unsupported intent / coverage gap. Improvement: extend schema-grounded intent mapping and add a regression test.")
    else: out.append('- No baseline failures; add ambiguous or unsupported natural-language questions to assess failure modes before claiming robust performance.')
    out += ['', '## Limitation','', 'This is a deterministic intent-mapping evaluation harness, not a live LLM call. `correct` measures mapped intent coverage plus successful execution, not semantic equivalence against all gold result bindings. To satisfy a requirement for real LLM evaluation, integrate the course-approved model, preserve raw output, and compare result sets with the reference queries.','']
    (BASE/'reports/t2s_run.md').write_text('\n'.join(out),encoding='utf-8'); print('\n'.join(out))

def main():
    p=argparse.ArgumentParser(); p.add_argument('--check-data',action='store_true'); p.add_argument('--queries',action='store_true'); p.add_argument('--shacl',action='store_true'); p.add_argument('--t2s',action='store_true'); p.add_argument('--all',action='store_true'); a=p.parse_args()
    if not any([a.check_data,a.queries,a.shacl,a.t2s,a.all]): a.all=True
    if a.check_data or a.all: check_data()
    if a.queries or a.all: run_queries()
    if a.shacl or a.all:
      rc=run_shacl()
      if rc==2: print('Skipping SHACL; install requirements then rerun --shacl.')
    if a.t2s or a.all: evaluate_t2s()
if __name__=='__main__': main()
